"""Area `context`: keep what loads into every session small, measured and enforced.

Layers (CAOS ADR-0080): L0 is always loaded (the rendered user core, the project CLAUDE.md chain, unscoped rules and
the project's MEMORY.md index); L1 is path-scoped (`.claude/rules/<id>.md` with `paths` front matter, loaded only with
a matching file); L2 is indexed on demand (reference files listed in an index with triggers).

Verbs:
    build    render the index, the L1 stubs and the L0 core from a knowledge manifest (C12), within its budget
    render   fill a template's `{{name}}` placeholders from a values file (for the user core template)
    check    fail when the always-loaded context exceeds its budgets (C01) or a MEMORY.md exceeds Claude Code's cap
    measure  print the session-start payload breakdown (informational)

Claude Code loads user and project CLAUDE.md files and unscoped rules in full, and only the first 200 lines or
25 KB of each project's MEMORY.md (code.claude.com/docs/en/memory). Token counts here are bytes / 4, an estimate.
Exit codes: 0 ok, 1 failure or refusal, 2 warnings.
"""
import json
import re
from pathlib import Path

from batuta_lib import config
from batuta_lib import contract as core
from batuta_lib import render
from batuta_lib.output import emit, item

AREA = "context"
HELP = "Context budget: build the knowledge index and core, check and measure what loads at session start."

MEMORY_CAP_BYTES = 25000
MEMORY_CAP_LINES = 200
KIND_SECTIONS = (("rule", "Rules"), ("procedure", "Procedures"), ("decision", "Decisions"),
                 ("memory", "Memories"), ("reference", "References"))
STUB_MARK = "<!-- generated by batuta context build -->"
CORE_HEADER = ("# Core rules\n<!-- Generated by batuta context build from the load: always units of the knowledge "
               "manifest. Edit the unit files and the manifest, not this file. -->\n")
INDEX_HEADER = ("# Knowledge index\n\n> Generated from the knowledge manifest by `batuta context build`; do not edit. "
                "Open a unit when its triggers match the task.\n")
ADVICE_CORE = "demote them to a reference file listed in the index (L2, read on demand) or a path-scoped rule (L1)"


# ------------------------------------------------------------------ shared helpers


def estimate_tokens(n_bytes):
    """Token estimate: bytes divided by 4, rounded up. Always an estimate."""
    return -(-int(n_bytes) // 4)


def sanitize(text):
    """Claude Code's project folder name: every character that is not a letter or digit becomes a hyphen."""
    return re.sub(r"[^A-Za-z0-9]", "-", str(text))


def project_key(path):
    return sanitize(Path(path).resolve())


def _flag_json(args):
    return bool(getattr(args, "json", False))


def _validated(path, cid):
    """The JSON file at `path` validated against contract `cid`; ValueError with the reason otherwise."""
    p = Path(path)
    try:
        doc = core.loads_strict(p.read_text(encoding="utf-8-sig"))
    except OSError as exc:
        raise ValueError(f"cannot read {p.as_posix()}: {exc}") from exc
    except ValueError as exc:
        raise ValueError(f"{p.as_posix()}: invalid JSON ({exc})") from exc
    sp = core.find_schema(config.contracts_dir(), cid)
    errors = core.validate_instance(cid, doc, core.load_schema(sp))
    if errors:
        raise ValueError(f"{p.as_posix()} does not satisfy {cid}: " + "; ".join(errors))
    return doc


def largest_sections(text, n=3):
    """The `n` largest H2 sections of a markdown text as (heading, bytes), largest first; a text without H2 headings
    is one section."""
    parts, name, buf = [], "(start of file)", []
    for line in text.splitlines(keepends=True):
        if line.startswith("## "):
            parts.append((name, "".join(buf)))
            name, buf = line[3:].strip(), [line]
        else:
            buf.append(line)
    parts.append((name, "".join(buf)))
    sized = [(h, len(b.encode("utf-8"))) for h, b in parts if b.strip()]
    return sorted(sized, key=lambda x: (-x[1], x[0]))[:n]


# ------------------------------------------------------------------ build


def _check_units(manifest_path, doc):
    """Problems of the unit files: (problems, {id: text}). A file must exist inside the manifest's folder."""
    base = manifest_path.parent.resolve()
    problems, texts = [], {}
    for u in doc["units"]:
        target = (base / u["file"]).resolve()
        try:
            target.relative_to(base)
        except ValueError:
            problems.append(f"unit '{u['id']}': file {u['file']} is outside the manifest folder")
            continue
        if not target.is_file():
            problems.append(f"unit '{u['id']}': file not found: {u['file']}")
            continue
        try:
            texts[u["id"]] = render.normalise(target.read_text(encoding="utf-8-sig"))
        except (OSError, UnicodeDecodeError) as exc:
            problems.append(f"unit '{u['id']}': cannot read {u['file']}: {exc}")
    return problems, texts


def _index_line(u):
    notes = [f"Load: {u['load']}"]
    if u.get("triggers"):
        notes.append("Triggers: " + ", ".join(u["triggers"]))
    if u.get("paths"):
        notes.append("Paths: " + ", ".join(u["paths"]))
    if u.get("requires"):
        notes.append("Requires: " + ", ".join(sorted(u["requires"])))
    return f"- [{u['title']}]({u['file']}): {u['summary']} ({'; '.join(notes)})"


def render_index(units):
    out = [INDEX_HEADER]
    for kind, heading in KIND_SECTIONS:
        members = sorted((u for u in units if u["kind"] == kind), key=lambda u: u["id"])
        if members:
            out.append(f"## {heading}\n")
            out.extend(_index_line(u) for u in members)
            out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def render_core(units, texts):
    out = [CORE_HEADER]
    for u in sorted((u for u in units if u["load"] == "always"), key=lambda u: u["id"]):
        out.append(f"## {u['title']}\n\n{texts[u['id']].strip(chr(10))}\n")
    return "\n".join(out).rstrip("\n") + "\n"


def _yaml_quote(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_stub(u, by_id):
    lines = ["---", "paths:", *[f"  - {_yaml_quote(p)}" for p in u["paths"]], "---", STUB_MARK,
             f"# {u['title']}", "", u["summary"], "", f"Full text: `{u['file']}`; read it when this rule applies."]
    if u.get("requires"):
        lines.append("Also read: " + ", ".join(f"`{by_id[r]['file']}`" for r in sorted(u["requires"])) + ".")
    return "\n".join(lines) + "\n"


def _demotion_advice(units, texts):
    always = sorted(((len(texts[u["id"]].encode("utf-8")), u["id"]) for u in units if u["load"] == "always"), reverse=True)
    top = ", ".join(f"{uid} ({size} bytes)" for size, uid in always[:3])
    return f"largest always-loaded units: {top}; set load to trigger (L2) or path (L1) for the ones not needed in every task"


def _build(args):
    items, as_json = [], _flag_json(args)

    def done(summary):
        return emit(AREA, "build", items, summary, as_json)

    try:
        cfg = config.load(getattr(args, "config", None)).config
    except config.ConfigError as exc:
        items.append(item("FAIL", str(exc)))
        return done("context build: failed")
    manifest = Path(args.manifest) if args.manifest else Path.cwd() / cfg["knowledge_manifest"]
    if not manifest.is_file():
        items.append(item("FAIL", f"knowledge manifest not found; expected {manifest.as_posix()}"))
        return done("context build: failed")
    try:
        doc = _validated(manifest, "C12")
    except ValueError as exc:
        items.append(item("FAIL", str(exc)))
        return done("context build: failed")
    problems, texts = _check_units(manifest, doc)
    if problems:
        items.extend(item("FAIL", p) for p in problems)
        return done("context build: failed")

    units = doc["units"]
    by_id = {u["id"]: u for u in units}
    out_dir = Path(args.out) if args.out else manifest.parent / "rendered"
    files = {out_dir / "INDEX.md": render_index(units), out_dir / "CORE.md": render_core(units, texts)}
    for u in units:
        if u["load"] == "path":
            files[out_dir / "rules" / f"{u['id']}.md"] = render_stub(u, by_id)

    core_bytes = len(files[out_dir / "CORE.md"].encode("utf-8"))
    index_bytes = len(files[out_dir / "INDEX.md"].encode("utf-8"))
    refused = False
    if core_bytes > doc["budget"]["core_bytes"]:
        items.append(item("REFUSED", f"core is {core_bytes} bytes, over the budget {doc['budget']['core_bytes']}; "
                                     + _demotion_advice(units, texts)))
        refused = True
    if index_bytes > doc["budget"]["index_bytes"]:
        items.append(item("REFUSED", f"index is {index_bytes} bytes, over the budget {doc['budget']['index_bytes']}; "
                                     "shorten summaries or split the manifest"))
        refused = True
    if refused:
        return done("context build: refused, nothing written")

    stale = []
    rules_dir = out_dir / "rules"
    if rules_dir.is_dir():
        for p in sorted(rules_dir.glob("*.md")):
            if p not in files and STUB_MARK in p.read_text(encoding="utf-8", errors="replace"):
                stale.append(p)
    for path, text in sorted(files.items()):
        items.append(item(render.status(path, text), path.relative_to(out_dir).as_posix()))
    items.extend(item("REMOVED", p.relative_to(out_dir).as_posix()) for p in stale)
    estimate = f"core {core_bytes} bytes (about {estimate_tokens(core_bytes)} tokens, estimate), index {index_bytes} bytes"
    if not args.apply:
        return done(f"context build: dry run, nothing written (use --apply); {estimate}")
    for path, text in files.items():
        if render.status(path, text) != "SAME":
            render.write_atomic(path, text)
    for p in stale:
        p.unlink()
    return done(f"context build: written; {estimate}")


def _render(args):
    items, as_json = [], _flag_json(args)
    try:
        values = json.loads(Path(args.values).read_text(encoding="utf-8-sig"))
        if not isinstance(values, dict):
            raise ValueError("the values file must hold one JSON object of name: text")
        text = render.render_file(args.template, values)
    except (OSError, ValueError, render.RenderError) as exc:
        items.append(item("FAIL", f"cannot render {Path(args.template).as_posix()}: {exc}"))
        return emit(AREA, "render", items, "context render: failed", as_json)
    out = Path(args.out)
    items.append(item(render.status(out, text), out.as_posix()))
    if args.apply and render.status(out, text) != "SAME":
        render.write_atomic(out, text)
    summary = "context render: written" if args.apply else "context render: dry run, nothing written (use --apply)"
    return emit(AREA, "render", items, f"{summary}; {len(text.encode('utf-8'))} bytes", as_json)


# ------------------------------------------------------------------ check and measure


class Entry:
    """One file that loads (or may load) at session start."""

    def __init__(self, group, path, size, lines, layer, text="", mine=True):
        self.group, self.path, self.size, self.lines, self.layer, self.text = group, Path(path), size, lines, layer, text
        self.mine = mine  # a memory index of this project (False: another project's)


def _read_entry(group, path, layer):
    try:
        data = Path(path).read_bytes()
    except OSError:
        return None
    text = data.decode("utf-8", errors="replace")
    return Entry(group, path, len(data), len(text.splitlines()), layer, text)


def _scoped(text):
    """True when a rule file has `paths` in its front matter (path-scoped, L1)."""
    lines = text.lstrip("\ufeff").splitlines()
    if not lines or lines[0].strip() != "---":
        return False
    for line in lines[1:]:
        if line.strip() == "---":
            return False
        if re.match(r"paths\s*:", line):
            return True
    return False


def _rules(group, rules_dir):
    out = []
    if rules_dir.is_dir():
        for p in sorted(rules_dir.rglob("*.md")):
            e = _read_entry(group, p, "L0")
            if e:
                if _scoped(e.text):
                    e.layer = "L1"
                out.append(e)
    return out


def _is_within(path, folder):
    try:
        Path(path).resolve().relative_to(Path(folder).resolve())
        return True
    except (ValueError, OSError):
        return False


def _chain(project, chain_root, exclude):
    """Project CLAUDE.md files from the project folder up to `chain_root` (default: the filesystem root)."""
    start = Path(project).resolve()
    dirs = [start, *start.parents]
    if chain_root is not None:
        root = Path(chain_root).resolve()
        if root in dirs:
            dirs = dirs[:dirs.index(root) + 1]
    entries = []
    for d in dirs:
        for rel in ("CLAUDE.md", ".claude/CLAUDE.md", "CLAUDE.local.md"):
            p = d / rel
            try:
                if p.is_file() and not _is_within(p, exclude):
                    e = _read_entry("project core", p, "L0")
                    if e:
                        entries.append(e)
            except OSError:
                continue
        for e in _rules("project rules", d / ".claude" / "rules"):
            if not _is_within(e.path, exclude):
                entries.append(e)
    return entries


def _memory_dirs(home, project, explicit):
    """[(memory dir, is this project's)] for the explicit folders and every project folder under `<home>/.claude/projects`."""
    wanted = {sanitize(d).lower() for d in (Path(project).resolve(), *Path(project).resolve().parents)}
    found, seen = [], set()
    for d in explicit or []:
        found.append((Path(d), True))
        seen.add(Path(d).resolve())
    base = Path(home) / ".claude" / "projects"
    if base.is_dir():
        for p in sorted(base.iterdir()):
            mem = p / "memory"
            if mem.is_dir() and mem.resolve() not in seen:
                found.append((mem, p.name.lower() in wanted))
    return found


def _collect(args, cfg):
    home = Path(args.home) if args.home else Path.home()
    user_core = Path(args.user_core) if args.user_core else home / ".claude" / "CLAUDE.md"
    entries = {"user core": [], "user rules": [], "project core": [], "project rules": [], "memory": []}
    e = _read_entry("user core", user_core, "L0") if user_core.is_file() else None
    if e:
        entries["user core"].append(e)
    entries["user rules"] = _rules("user rules", home / ".claude" / "rules")
    for e in _chain(args.project, args.chain_root, home / ".claude"):
        entries[e.group].append(e)
    skipped, own = [], 0
    for mem, mine in _memory_dirs(home, args.project, args.memory_dir):
        idx = mem / "MEMORY.md"
        e = _read_entry("memory" if mine else "other memory", idx, "L0") if idx.is_file() else None
        if e is None:
            if mine:
                skipped.append(mem)
            continue
        e.mine = mine
        entries["memory"].append(e)
        own += 1 if mine else 0
    return user_core, entries, skipped, own


def _fail_text(label, size, budget, extra):
    return f"{label} is {size} bytes, over the budget {budget} by {size - budget}; {extra}"


def _advice_sections(entries):
    parts = []
    for e in entries:
        for heading, size in largest_sections(e.text, 2):
            parts.append((size, f'"{heading}" in {e.path.name}'))
    parts.sort(reverse=True)
    return "largest sections: " + ", ".join(f"{name} ({size} bytes)" for size, name in parts[:3]) + "; " + ADVICE_CORE


def _advice_files(entries):
    top = sorted(entries, key=lambda e: (-e.size, e.path.name))[:3]
    return ("largest files: " + ", ".join(f"{e.path.name} ({e.size} bytes)" for e in top)
            + "; add `paths` front matter to scope a rule to files (L1) or move it to a reference file (L2)")


def _check(args):
    items, as_json = [], _flag_json(args)

    def done(summary):
        return emit(AREA, "check", items, summary, as_json)

    try:
        cfg = config.load(getattr(args, "config", None), project_root=args.project).config
    except config.ConfigError as exc:
        items.append(item("FAIL", str(exc)))
        return done("context check: failed")
    budgets = cfg["budgets"]
    user_core, entries, skipped, own = _collect(args, cfg)

    if entries["user core"]:
        e = entries["user core"][0]
        label = f"user core ({e.path.name})"
        if e.size > budgets["user_core_bytes"]:
            items.append(item("FAIL", _fail_text(label, e.size, budgets["user_core_bytes"], _advice_sections([e])), e.path.as_posix()))
        else:
            items.append(item("OK", f"{label}: {e.size} of {budgets['user_core_bytes']} bytes (about {estimate_tokens(e.size)} tokens, estimate)", e.path.as_posix()))
    else:
        items.append(item("MISSING", f"user core not found: {user_core.as_posix()}"))

    for group in ("user rules", "project rules"):
        loaded = [e for e in entries[group] if e.layer == "L0"]
        total = sum(e.size for e in loaded)
        if total > budgets["unscoped_rules_bytes"]:
            items.append(item("FAIL", _fail_text(f"unscoped {group}", total, budgets["unscoped_rules_bytes"], _advice_files(loaded))))
        elif loaded:
            items.append(item("OK", f"unscoped {group}: {total} of {budgets['unscoped_rules_bytes']} bytes in {len(loaded)} file(s)"))

    chain = entries["project core"]
    total = sum(e.size for e in chain)
    if total > budgets["project_core_bytes"]:
        items.append(item("FAIL", _fail_text("project CLAUDE.md chain", total, budgets["project_core_bytes"], _advice_sections(chain))))
    elif chain:
        items.append(item("OK", f"project CLAUDE.md chain: {total} of {budgets['project_core_bytes']} bytes in {len(chain)} file(s)"))
    else:
        items.append(item("OK", "SKIP no project CLAUDE.md found in the chain"))

    for e in entries["memory"]:
        where = e.path.as_posix()
        over_cap = e.size > MEMORY_CAP_BYTES or e.lines > MEMORY_CAP_LINES
        over_budget = e.size > budgets["memory_index_bytes"] or e.lines > budgets["memory_index_lines"]
        measured = f"{e.size} bytes, {e.lines} lines"
        budget_text = f"budget {budgets['memory_index_bytes']} bytes, {budgets['memory_index_lines']} lines"
        if over_cap:
            items.append(item("FAIL", f"{e.group} index {measured}: over Claude Code's load cap of {MEMORY_CAP_LINES} lines or "
                                      f"{MEMORY_CAP_BYTES} bytes, the rest is silently dropped; run `memory index` so topic pages (L2) absorb entries", where))
        elif over_budget and e.mine:
            items.append(item("FAIL", f"{e.group} index {measured}: over the {budget_text}; run `memory index --apply` so topic pages (L2) absorb entries", where))
        elif over_budget:
            items.append(item("WARN", f"{e.group} index {measured}: over the {budget_text} (under the load cap); run `memory index`", where))
        else:
            items.append(item("OK", f"{e.group} index {measured}: within the {budget_text}", where))
    if own == 0:
        reason = "no MEMORY.md" if skipped else "no memory folder"
        items.append(item("OK", f"SKIP {reason} for project {Path(args.project).name}"))
    return done("context check: " + ("budgets exceeded" if any(i["tag"] in ("FAIL", "REFUSED") for i in items) else "within budget"))


def _measure(args):
    items, as_json = [], _flag_json(args)
    try:
        cfg = config.load(getattr(args, "config", None), project_root=args.project).config
    except config.ConfigError as exc:
        items.append(item("FAIL", str(exc)))
        return emit(AREA, "measure", items, "context measure: failed", as_json)
    _, entries, _, _ = _collect(args, cfg)
    total = 0
    for group in ("user core", "user rules", "project core", "project rules", "memory"):
        for e in entries[group]:
            size = min(e.size, MEMORY_CAP_BYTES) if group == "memory" else e.size
            if e.layer == "L0":
                total += size
            items.append(item("OK", f"{e.layer} {e.group}: {size} bytes, about {estimate_tokens(size)} tokens (estimate)", e.path.as_posix()))
    return emit(AREA, "measure", items, f"total at session start (L0): {total} bytes, about {estimate_tokens(total)} tokens "
                                         "(estimate: bytes / 4); L1 files load only with a matching file", as_json)


def register(subparsers):
    p = subparsers.add_parser("build", help="render the index, the path-scoped stubs and the core from a knowledge manifest (C12)")
    p.add_argument("--manifest", help="the knowledge manifest (default: knowledge_manifest of batuta.json under the current folder)")
    p.add_argument("--out", help="output folder (default: <manifest folder>/rendered)")
    p.add_argument("--apply", action="store_true", help="write the files (default: dry run)")
    p.set_defaults(func=_build)

    p = subparsers.add_parser("render", help="fill a template's {{name}} placeholders from a JSON values file")
    p.add_argument("--template", required=True, help="the template file")
    p.add_argument("--values", required=True, help="a JSON object of placeholder values")
    p.add_argument("--out", required=True, help="the file to write")
    p.add_argument("--apply", action="store_true", help="write the file (default: dry run)")
    p.set_defaults(func=_render)

    for name, func, text in (("check", _check, "fail when the always-loaded context exceeds its budgets"),
                             ("measure", _measure, "print the session-start payload breakdown")):
        p = subparsers.add_parser(name, help=text)
        p.add_argument("--project", default=".", help="project folder (default: the current folder)")
        p.add_argument("--home", help="home folder holding .claude/ (default: the user's home)")
        p.add_argument("--user-core", help="the user core file (default: <home>/.claude/CLAUDE.md)")
        p.add_argument("--memory-dir", action="append", help="a memory folder of this project (repeatable); "
                                                              "default: found under <home>/.claude/projects")
        p.add_argument("--chain-root", help="stop the CLAUDE.md chain at this folder, inclusive (default: the filesystem root)")
        p.set_defaults(func=func)
