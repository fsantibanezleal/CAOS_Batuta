"""Generate a project's auto-memory index (MEMORY.md) as a short index plus topic pages.

Claude Code loads only the first 200 lines or 25 KB of MEMORY.md at every session start; the other files of the
memory folder are read on demand. This module keeps MEMORY.md small (pinned memories plus one line per topic) and
builds one page per topic (`topics/<id>.md`) listing its memories, so the per-memory lines are read only when the
task matches. Pure functions, deterministic, standard library only; the `memory index` verb
(`batuta_lib/areas/memory.py`) does the reading of contracts, the budget gate and the writing.
"""
import re
from pathlib import Path

GENERATED_PREFIX = "# Memory index (generated by"
PAGE_MARK = "<!-- generated by batuta memory index -->"
GENERATED_HEADER = GENERATED_PREFIX + " batuta memory index; edit the memories or the topics file, not this file)"
# Separators of an index entry: " - ", " -- ", ": " or a space, an em-dash and a space (written as an escape).
ENTRY_RE = re.compile(r"^[-*+] \[(?P<title>[^\]]+)\]\((?:\.\./)?(?P<stem>[^)/]+)\.md\)(?: - | -- |: | \u2014 )?(?P<hook>.*)$")
KEY_RE = re.compile(r"^(?P<key>[A-Za-z_][\w-]*):[ \t]*(?P<value>.*)$")
NESTED_RE = re.compile(r"^[ \t]+(?P<key>[A-Za-z_][\w-]*):[ \t]*(?P<value>.*)$")
BOM = "\ufeff"


def _read(path):
    return Path(path).read_text(encoding="utf-8-sig")


def _unquote(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] == '"':
        return value[1:-1].replace('\\"', '"').replace("\\\\", "\\")
    if len(value) >= 2 and value[0] == value[-1] == "'":
        return value[1:-1].replace("''", "'")
    return value


def parse_frontmatter(text):
    """Top-level `name` and `description` and the `type` nested under `metadata` (or top-level)."""
    lines = text.lstrip(BOM).splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    out = {}
    in_metadata = False
    for line in lines[1:]:
        if line.strip() == "---":
            break
        top = KEY_RE.match(line)
        if top:
            key = top.group("key")
            in_metadata = key == "metadata"
            if not in_metadata:
                out[key] = _unquote(top.group("value"))
            continue
        nested = NESTED_RE.match(line)
        if nested and in_metadata and nested.group("key") == "type":
            out["type"] = _unquote(nested.group("value"))
    return out


def parse_index(text):
    """Entries `{stem: (title, hook)}` and the non-entry lines (headings and blanks included)."""
    entries, other = {}, []
    for line in text.splitlines():
        match = ENTRY_RE.match(line)
        if match:
            entries.setdefault(match.group("stem"), (match.group("title").strip(), match.group("hook").strip()))
        else:
            other.append(line)
    return entries, other


def _notes_of(text, other):
    """Lines kept verbatim under Notes: of a hand-written index every line that is not a heading or blank; of a
    generated index only its own Notes section."""
    if text.lstrip(BOM).startswith(GENERATED_PREFIX):
        if "## Notes" not in other:
            return []
        other = other[other.index("## Notes") + 1:]
    return [line for line in other if line.strip() and not line.lstrip().startswith("#")]


def trim(text, limit):
    """Trim to `limit` characters at a word boundary, ending with `...` when cut."""
    text = " ".join(text.split())
    if len(text) <= limit:
        return text
    keep = max(limit - 3, 0)
    cut = text[:keep]
    if keep < len(text) and text[keep] != " " and " " in cut:
        cut = cut.rsplit(" ", 1)[0]
    return cut.rstrip(" ,;:-") + "..."


def classify(stem, project_cfg):
    """`pinned`, the id of the first topic whose `match` regex is found in the stem, or `other`."""
    if stem in project_cfg.get("pinned", []):
        return "pinned"
    for topic in project_cfg.get("topics", []):
        if any(re.search(pattern, stem) for pattern in topic.get("match", [])):
            return topic["id"]
    return "other"


def _words(name):
    text = re.sub(r"[-_]+", " ", name).strip()
    return text[:1].upper() + text[1:]


def _load_old(memory_dir, page_ids):
    """Old entries from MEMORY.md and from the topic pages, and the Notes lines of the old index.

    Only pages this tool wrote are read: a page carrying the mark, or, when migrating (`page_ids` not empty), an
    unmarked page named like a topic id (pages written before the mark existed). A hand-written file in `topics/` is
    never a source of entries."""
    entries, notes = {}, []
    index = memory_dir / "MEMORY.md"
    if index.is_file():
        text = _read(index)
        entries, other = parse_index(text)
        notes = _notes_of(text, other)
    topics = memory_dir / "topics"
    if topics.is_dir():
        for page in sorted(topics.glob("*.md")):
            text = _read(page)
            if page.stem not in page_ids and PAGE_MARK not in text:
                continue
            for stem, value in parse_index(text)[0].items():
                entries.setdefault(stem, value)
    return entries, notes


def build(memory_dir, project_cfg, cfg, adopt_legacy=False):
    """Return `(index_text, pages, report)` for one memory folder. Writes nothing.

    `adopt_legacy` also reads unmarked pages named like a topic id (pages written before the generation mark)."""
    memory_dir = Path(memory_dir)
    hook_max = int(cfg.get("hook_max_chars", 110))
    title_max = int(cfg.get("title_max_chars", 60))
    stems = sorted(p.stem for p in memory_dir.glob("*.md") if p.name != "MEMORY.md")
    page_ids = ({t["id"] for t in project_cfg.get("topics", [])} | {"other"}) if adopt_legacy else set()
    old, notes = _load_old(memory_dir, page_ids)

    lines = {}
    for stem in stems:
        if stem in old:
            title, hook = old[stem]
        else:
            fm = parse_frontmatter(_read(memory_dir / f"{stem}.md"))
            title, hook = _words(fm.get("name") or stem), fm.get("description", "")
        lines[stem] = (trim(title, title_max), trim(hook, hook_max))

    def line(stem, prefix):
        title, hook = lines[stem]
        return f"- [{title}]({prefix}{stem}.md)" + (f" - {hook}" if hook else "")

    groups = {}
    for stem in stems:
        groups.setdefault(classify(stem, project_cfg), []).append(stem)

    pinned = [s for s in project_cfg.get("pinned", []) if s in lines]
    order = [(t["id"], t["title"], t["when"]) for t in project_cfg.get("topics", [])]
    other_cfg = project_cfg.get("other", {"title": "Other", "when": "when no topic above fits"})
    order.append(("other", other_cfg.get("title", "Other"), other_cfg.get("when", "when no topic above fits")))

    out = [GENERATED_HEADER, "## Always relevant", *[line(s, "") for s in pinned]]
    out.append("## Topics (open the page when the task matches)")
    pages = {}
    counts = {"pinned": len(pinned)}
    for tid, title, when in order:
        members = groups.get(tid, [])
        counts[tid] = len(members)
        if not members:
            continue
        out.append(f"- [{title} ({len(members)})](topics/{tid}.md) - {when}")
        body = [f"# {title}", PAGE_MARK, "", f"Read when: {when}.", "", *[line(s, "../") for s in members]]
        pages[tid] = "\n".join(body) + "\n"
    if notes:
        out += ["## Notes", *notes]
    index_text = "\n".join(out) + "\n"

    seen = list(pinned) + [s for tid, _, _ in order for s in groups.get(tid, [])]
    if sorted(seen) != stems:
        raise RuntimeError("completeness guard failed: a memory file is missing or listed twice")
    report = {
        "files": len(stems),
        "counts": counts,
        "dangling": sorted(s for s in old if s not in lines),
        "missing_pins": [s for s in project_cfg.get("pinned", []) if s not in lines],
        "index_bytes": len(index_text.encode("utf-8")),
        "index_lines": len(index_text.splitlines()),
    }
    return index_text, pages, report


def render_report(report):
    rows = [f"files: {report['files']}"]
    rows += [f"  {tid}: {n}" for tid, n in report["counts"].items()]
    rows.append(f"index: {report['index_bytes']} bytes, {report['index_lines']} lines")
    rows += [f"DANGLING (old entry, no file, dropped): {stem}" for stem in report["dangling"]]
    rows += [f"MISSING PIN (pinned, no file): {stem}" for stem in report["missing_pins"]]
    return "\n".join(rows)
